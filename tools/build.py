def _src(text):
    text = textwrap.dedent(text).strip("\n")
    lines = text.split("\n")
    return [l + "\n" for l in lines[:-1]] + [lines[-1]]


def M(text):
    """説明 (Markdown)。両方に同じものを入れる"""
    return ("md", text, text, [])


def C(code):
    """見本のコード。両方に同じものを入れる"""
    return ("code", code, code, [])


def X(code):
    """わざとエラーを見せるコード。両方とも、実行するとエラーになる"""
    return ("code", code, code, ["raises-exception"])


def E(student, solution):
    """演習。受講者用は空欄、解答例には答え"""
    return ("code", student, solution, [])


def B(student, solution):
    """エラー直し。受講者用は壊れたまま (実行するとエラー)、解答例は直したもの"""
    return ("code", student, solution, ["raises-exception", "fix-me"])


def build(cells, solution):
    out = []
    for kind, stu, sol, tags in cells:
        text = sol if solution else stu
        if kind == "md":
            out.append({"cell_type": "markdown", "metadata": {}, "source": _src(text)})
        else:
            t = list(tags)
            if solution and "fix-me" in t:
                t = []  # 直したので、もうエラーにならない
            meta = {"tags": t} if t else {}
            out.append({"cell_type": "code", "execution_count": None, "metadata": meta,
                        "outputs": [], "source": _src(text)})
    return {
        "nbformat": 4, "nbformat_minor": 0,
        "metadata": {
            "colab": {"provenance": [], "toc_visible": True},
            "kernelspec": {"name": "python3", "display_name": "Python 3"},
            "language_info": {"name": "python"},
        },
        "cells": out,
    }


